#!/usr/bin/env node
// No external dependencies. Quickly audits this Mac's local development prerequisites.
import {existsSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {createServer} from 'node:net';

let blockers=0;
const line=(ok,label,note='')=>{console.log(`${ok?'PASS':'FAIL'}  ${label}${note?' · '+note:''}`);if(!ok)blockers++};
const nodeMajor=Number(process.versions.node.split('.')[0]);
line(nodeMajor>=22&&nodeMajor<25,'Node.js',process.version+' (requires 22.x to 24.x)');
const version=spawnSync('pnpm',['--version'],{encoding:'utf8',timeout:5000});
line(version.status===0&&version.stdout?.trim().startsWith('10.'),'pnpm',version.status===0?version.stdout.trim():'Run: corepack enable && corepack prepare pnpm@10.18.0 --activate');
line(existsSync('.env'),'Local .env',existsSync('.env')?'Present (secrets never printed)':'Run: cp .env.example .env');
line(existsSync('node_modules'),'Dependencies',existsSync('node_modules')?'Installed':'Run: pnpm install');
console.log(`${existsSync('pnpm-lock.yaml')?'PASS':'NOTE'}  Lockfile · ${existsSync('pnpm-lock.yaml')?'Present':'Generated by first online pnpm install; commit to version control'}`);
async function portFree(port){return new Promise(resolve=>{const srv=createServer();srv.once('error',()=>resolve(false));srv.listen(port,'127.0.0.1',()=>srv.close(()=>resolve(true)));});}
for(const port of [5173,8787]){const free=await portFree(port);console.log(`${free?'PASS':'NOTE'}  Port ${port} · ${free?'Free':'In use; shut down old dev process or confirm it is your active FluxDesk'}`);}
console.log(`\n${blockers===0?'Prerequisites appear ready. Next: pnpm check && pnpm dev':'Resolve FAIL items, then rerun: node scripts/doctor.mjs'}`);
process.exitCode=blockers?1:0;
